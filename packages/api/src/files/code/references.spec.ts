import type { CodeEnvRef, TFile } from 'librechat-data-provider';
import type { CodeFileReferences } from './references';
import { getTurnCodeEnvRef, saveCodeFileReference } from './references';

const file: TFile = {
  file_id: 'input',
  filename: 'data.csv',
  filepath: '/uploads/data.csv',
  type: 'text/csv',
  bytes: 12,
  user: 'user',
  embedded: false,
  object: 'file',
  usage: 0,
  updatedAt: '2026-10-01',
};
const ref: CodeEnvRef = {
  kind: 'user',
  id: 'user',
  file_id: 'remote',
  storage_session_id: 'store',
  sandboxFilename: 'data-alias.csv',
};

describe('turn code references', () => {
  it('keeps collision aliases scoped to the request, deployment, and content version', async () => {
    const req: { codeFileReferences?: CodeFileReferences } = {};
    const save = jest.fn();
    await saveCodeFileReference({ req, routeKey: 'default', file, ref, temporary: true, save });
    expect(save).not.toHaveBeenCalled();
    expect(getTurnCodeEnvRef(req, 'default', file, ref.sandboxFilename)).toEqual(ref);
    expect(getTurnCodeEnvRef({ ...req }, 'default', file)).toEqual(ref);
    expect(getTurnCodeEnvRef({}, 'default', file)).toBeUndefined();
    expect(getTurnCodeEnvRef(req, 'other', file)).toBeUndefined();
    expect(getTurnCodeEnvRef(req, 'default', { ...file, updatedAt: '2026-10-02' })).toBeUndefined();
  });

  it('invalidates an alias when generated bytes change while preserving it through preview writes', async () => {
    const req: { codeFileReferences?: CodeFileReferences } = {};
    const generated = { ...file, metadata: { sourceDispatchedAt: 10 } };
    await saveCodeFileReference({
      req,
      routeKey: 'default',
      file: generated,
      ref,
      temporary: true,
      save: jest.fn(),
    });
    expect(
      getTurnCodeEnvRef(req, 'default', { ...generated, updatedAt: '2026-10-02', status: 'ready' }),
    ).toEqual(ref);
    expect(
      getTurnCodeEnvRef(req, 'default', { ...generated, metadata: { sourceDispatchedAt: 11 } }),
    ).toBeUndefined();
  });

  it('persists ordinary references and propagates database failures', async () => {
    const req = {};
    const save = jest.fn().mockRejectedValue(new Error('database unavailable'));
    await expect(
      saveCodeFileReference({ req, routeKey: 'default', file, ref, temporary: false, save }),
    ).rejects.toThrow('database unavailable');
    expect(save).toHaveBeenCalledTimes(1);
    expect(getTurnCodeEnvRef(req, 'default', file)).toBeUndefined();
  });
});
